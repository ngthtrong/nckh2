#!/usr/bin/env python3
"""Export only the independently checked, separately scoped public-data pilot."""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/revision-plan/outputs/multimodal-20261108'
OUT = ROOT / 'report/generated'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(name):
    with (SOURCE / name).open(newline='') as f:
        return list(csv.DictReader(f))


def number(value):
    return f'{float(value):.2f}'.replace('.', ',')


def main():
    verification = json.loads((SOURCE / 'verification.json').read_text())
    assert verification['status'] == 'PASS_PUBLIC_PILOT'
    for relative, expected in verification['result_hashes'].items():
        assert sha(ROOT / relative) == expected, f'Changed pilot input: {relative}'
    metrics = {r['model']: r for r in read_csv('metrics.csv')}
    effects = read_csv('paired-effects.csv')
    audit = json.loads((SOURCE / 'data-audit.json').read_text())
    evaluation = json.loads((SOURCE / 'evaluation.json').read_text())
    macros = ['% Generated by scripts/export_multimodal.py; do not edit.']
    for suffix, key in [('TrainN', 'train'), ('DevN', 'dev'), ('TestN', 'test')]:
        macros.append(r'\providecommand{\MM' + suffix + '}{' + str(audit['split_counts'][key]) + '}')
    macros.append(r'\providecommand{\MMTestGroups}{' + str(evaluation['duplicate_groups']) + '}')
    for prefix, name in [('Text', 'text_tfidf_lr'), ('Image', 'image_frozen_lr'), ('Fusion', 'feature_concat_lr'), ('Mean', 'mean_probability')]:
        macros.append(r'\providecommand{\MM' + prefix + 'FOne}{' + number(100 * float(metrics[name]['macro_f1'])) + '}')
    for prefix, comparator in [('Text', 'text_tfidf_lr'), ('Image', 'image_frozen_lr'), ('Mean', 'mean_probability')]:
        effect = next(r for r in effects if r['contrast'].endswith(' - ' + comparator))
        for suffix, key in [('Delta', 'delta_macro_f1'), ('Low', 'ci95_low'), ('High', 'ci95_high')]:
            macros.append(r'\providecommand{\MMFusion' + prefix + suffix + '}{' + number(100 * float(effect[key])) + '}')
    (OUT / 'multimodal-values.tex').write_text('\n'.join(macros) + '\n')
    names = [('majority', 'Lớp đa số'), ('text_tfidf_lr', 'Text TF-IDF + LR'),
             ('image_frozen_lr', 'Ảnh frozen + LR'), ('mean_probability', 'Trung bình xác suất'),
             ('feature_concat_lr', 'Nối đặc trưng + LR'), ('concat_missing_image', 'Fusion thiếu ảnh'), ('concat_missing_text', 'Fusion thiếu text')]
    table = [r'% Generated by scripts/export_multimodal.py; do not edit.',
             r'\begin{table}[htbp]\centering',
             r'\caption{Pilot CrisisMMD trên sự kiện lũ Sri Lanka; hai hàng cuối che modality khi suy luận}\label{tab:multimodal-pilot}',
             r'\begin{tabular}{lrrr}\toprule',
             r'Cấu hình & Macro-F1 (\%) & Accuracy (\%) & Recall (+) (\%) \\ \midrule']
    for name, label in names:
        table.append(' & '.join([label] + [number(100 * float(metrics[name][k])) for k in ['macro_f1', 'accuracy', 'recall_informative']]) + r' \\')
    table.extend([r'\bottomrule\end{tabular}', r'\end{table}'])
    (OUT / 'tables/multimodal-pilot.tex').write_text('\n'.join(table) + '\n')
    ci = [r'% Generated by scripts/export_multimodal.py; do not edit.',
          r'\begin{table}[htbp]\centering',
          r'\caption{Hiệu macro-F1 của fusion nối đặc trưng: bootstrap ghép cặp theo nhóm bản trùng, CI 95\% chưa hiệu chỉnh}\label{tab:multimodal-effects}',
          r'\begin{tabular}{lrrr}\toprule', r'Đối chứng & Hiệu (đpt) & Cận dưới & Cận trên \\ \midrule']
    for r, label in zip(effects, ['Text', 'Ảnh', 'Trung bình xác suất']):
        ci.append(' & '.join([label] + [number(100 * float(r[k])) for k in ['delta_macro_f1', 'ci95_low', 'ci95_high']]) + r' \\')
    ci.extend([r'\bottomrule\end{tabular}', r'\end{table}'])
    (OUT / 'tables/multimodal-effects.tex').write_text('\n'.join(ci) + '\n')
    files = [SOURCE / 'verification.json', Path(__file__)] + [ROOT / p for p in verification['result_hashes']]
    (OUT / 'multimodal-provenance.json').write_text(json.dumps({str(p.relative_to(ROOT)): sha(p) for p in files}, indent=2) + '\n')
    print('Exported public pilot: 2 tables and scoped values')


if __name__ == '__main__':
    main()
