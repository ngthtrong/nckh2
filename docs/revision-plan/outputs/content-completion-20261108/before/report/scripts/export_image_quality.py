#!/usr/bin/env python3
"""Export the fixed-model CPU corruption screening from audited raw predictions."""
from pathlib import Path
import csv
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/revision-plan/outputs/followup-20261108/phase-04'
OUT = ROOT / 'report/generated'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rows(name):
    with (SOURCE / name).open(encoding='utf-8', newline='') as stream:
        return list(csv.DictReader(stream))


def number(value, digits=2):
    return f'{float(value):.{digits}f}'.replace('.', ',')


def main():
    validation = json.loads((SOURCE / 'validation.json').read_text())
    assert validation['status'] == 'PASS_CPU_ONLY' and validation['test_predictions'] == 2304
    gate = json.loads((SOURCE / 'clean-parity.json').read_text())
    assert gate['status'] == 'PASS_CPU_ONLY'
    for path, digest in json.loads((SOURCE / 'source-hashes.json').read_text()).items():
        assert sha(ROOT / path) == digest, f'Changed input: {path}'
    for path, digest in json.loads((SOURCE / 'result-hashes.json').read_text()).items():
        assert sha(ROOT / path) == digest, f'Changed result: {path}'
    metrics, predictions = rows('metrics.csv'), rows('predictions.csv')
    assert len(metrics) == 9 and len(predictions) == 2304
    by_condition = {r['condition']: r for r in metrics}
    for condition, summary in by_condition.items():
        selected = [r for r in predictions if r['condition'] == condition]
        assert len(selected) == len({r['id'] for r in selected}) == 256
        matrix = [[0] * 5 for _ in range(4)]
        ordinal = [1, 2, 3, 0]
        severe = 0
        for r in selected:
            actual, predicted = int(r['label_idx']), int(r['pred_idx'])
            matrix[actual][predicted if r['status'] == 'OK' else 4] += 1
            severe += r['status'] == 'OK' and abs(ordinal[actual] - ordinal[predicted]) >= 2
        accuracy = sum(matrix[i][i] for i in range(4)) / 256
        f1 = sum(2 * matrix[i][i] / (sum(matrix[i]) + sum(row[i] for row in matrix)) for i in range(4)) / 4
        recall = matrix[2][2] / sum(matrix[2])
        assert abs(accuracy - float(summary['accuracy'])) < 1e-12
        assert abs(f1 - float(summary['macro_f1'])) < 1e-12
        assert abs(recall - float(summary['recall_high'])) < 1e-12
        assert severe == int(summary['ordinal_error_ge2_count'])
    labels = ['Gốc', 'JPEG q50', 'JPEG q20', 'Cạnh ngắn 128', 'Cạnh ngắn 64',
              r'Mờ $\sigma=1$', r'Mờ $\sigma=2$', r'Độ sáng $\times0{,}7$', r'Độ sáng $\times0{,}4$']
    lines = [r'% Generated by scripts/export_image_quality.py; do not edit.',
             r'\begin{table}[htbp]\centering\small',
             r'\caption{Đánh giá ảnh suy giảm nhân tạo trên ONNX CPU: 256 ảnh test ghép cặp, seed 1024 cắt tỉa}\label{tab:image-quality-cpu}',
             r'\begin{tabular}{lrrrr}',
             r'\toprule Điều kiện & Accuracy (\%) & Macro-F1 (\%) & Recall high (\%) & Lỗi nặng \\',
             r'\midrule']
    for label, row in zip(labels, metrics):
        lines.append(' & '.join([label, number(100 * float(row['accuracy'])),
                                 number(100 * float(row['macro_f1'])),
                                 number(100 * float(row['recall_high'])),
                                 row['ordinal_error_ge2_count']]) + r' \\')
    lines += [r'\bottomrule\end{tabular}', r'\end{table}', '']
    (OUT / 'tables/image-quality-cpu.tex').write_text('\n'.join(lines))
    effects = rows('paired-effects.csv')
    macros = []
    for prefix, condition in [('Clean', 'clean'), ('Dark', 'exposure_0.4')]:
        row = by_condition[condition]
        for metric, suffix in [('accuracy', 'Accuracy'), ('macro_f1', 'MacroFOne'), ('recall_high', 'HighRecall')]:
            macros.append(r'\providecommand{\Quality' + prefix + suffix + '}{' + number(100 * float(row[metric])) + '}')
    for prefix, condition in [('Dark', 'exposure_0.4'), ('Blur', 'blur_sigma_2')]:
        effect = next(r for r in effects if r['condition'] == condition and r['metric'] == 'macro_f1')
        for field, suffix in [('delta_degraded_minus_clean', 'DeltaFOne'), ('ci_low', 'CILow'), ('ci_high', 'CIHigh')]:
            macros.append(r'\providecommand{\Quality' + prefix + suffix + '}{' + number(100 * float(effect[field])) + '}')
    (OUT / 'image-quality-values.tex').write_text('\n'.join(macros) + '\n')
    files = [SOURCE / name for name in ['protocol.json', 'source-hashes.json', 'result-hashes.json',
             'clean-parity.json', 'predictions.csv', 'metrics.csv', 'paired-effects.csv', 'validation.json']]
    files.append(Path(__file__))
    (OUT / 'image-quality-provenance.json').write_text(json.dumps(
        {str(p.relative_to(ROOT)): sha(p) for p in files}, indent=2) + '\n')
    print('Image quality CPU: 2304 prediction rows, nine conditions; raw metrics verified and exported.')


if __name__ == '__main__':
    main()
