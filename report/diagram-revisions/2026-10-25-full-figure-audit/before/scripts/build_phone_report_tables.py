"""Validate saved phone evidence and render main and appendix tables."""
import csv
import hashlib
import json
import math
from pathlib import Path
from statistics import mean
from highlight_results import highlight_results

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'report/generated/phone-benchmarks'
OUT = ROOT / 'report/generated/tables'
RANK = {'non_flood': 0, 'low': 1, 'medium': 2, 'high': 3}
DEVICE = {'realme15': 'RM15', 'redminote11': 'RN11', 'redminote13': 'RN13', 'samsungs10e': 'S10e'}
NAMES = {'realme15': 'realme 15', 'redminote11': 'Redmi Note 11', 'redminote13': 'Redmi Note 13', 'samsungs10e': 'Samsung S10e'}


def read(name):
    with (DATA / name).open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def fmt(value, digits=2):
    return f'{float(value):.{digits}f}'.replace('.', ',')


def code(r):
    return f"{r['seed']}-{'B' if r['variant'] == 'baseline' else 'P'}-{DEVICE[r['device']]}-{'O' if r['runtime'] == 'onnx' else 'T'}"


def table(name, caption, label, headers, rows, long=False):
    rows = highlight_results(name, rows)
    spec = 'l' + 'r' * (len(headers) - 1)
    header = ' & '.join(headers) + r' \\'
    lines = ['% Generated by scripts/build_phone_report_tables.py; do not edit.']
    if long:
        lines += [r'\begingroup\small\setlength{\tabcolsep}{4pt}', r'\begin{longtable}{' + spec + '}',
                  r'\caption{' + caption + r'}\label{' + label + r'}\\',
                  r'\toprule ' + header + r' \midrule\endfirsthead',
                  r'\multicolumn{' + str(len(headers)) + r'}{l}{\tablename~\thetable{} (tiếp)}\\',
                  r'\toprule ' + header + r' \midrule\endhead',
                  r'\midrule\multicolumn{' + str(len(headers)) + r'}{r}{Còn tiếp ở trang sau}\\\endfoot',
                  r'\bottomrule\endlastfoot']
    else:
        lines += [r'\begin{table}[htbp]\centering\small\setlength{\tabcolsep}{4pt}',
                  r'\caption{' + caption + r'}\label{' + label + '}',
                  r'\begin{tabular}{' + spec + '}', r'\toprule ' + header + r' \midrule']
    for index, row in enumerate(rows):
        lines.append(' & '.join(str(v) for v in row) + r' \\')
        if name == 'phone-selected-runtimes' and index % 2 == 1 and index < len(rows) - 1:
            lines.append(r'\midrule')
    lines += [r'\end{longtable}\endgroup' if long else r'\bottomrule\end{tabular}\end{table}', '']
    (OUT / (name + '.tex')).write_text('\n'.join(lines), encoding='utf-8')


def main():
    summary = read('summary.csv')
    classes = read('evaluate_model_phone/class_metrics.csv')
    predictions = read('evaluate_model_phone/predictions.csv')
    assert len(summary) == 32 and len(classes) == 128 and len(predictions) == 8192
    assert len({(r['seed'], r['variant'], r['device'], r['runtime']) for r in summary}) == 32
    severe = {}
    for r in summary:
        path = ROOT / r['source_json']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == r['source_sha256']
        d = json.loads(path.read_text(encoding='utf-8-sig'))
        p = d['predictions']
        saved = [x for x in predictions if x['source_json'] == r['source_json']]
        assert len(p) == len(saved) == 256 and d['complete'] and d['failedSamples'] == d['warmupErrors'] == 0
        assert {(x['id'], x['truth'], x['prediction']) for x in p} == {(x['id'], x['truth'], x['prediction']) for x in saved}
        distances = [abs(RANK[x['truth']] - RANK[x['prediction']]) for x in p]
        severe[r['source_json']] = sum(v >= 2 for v in distances)
        expected = dict(accuracy=d['accuracy'], macro_f1=d['macroF1'],
                        macro_precision=mean(v['precision'] for v in d['classMetrics'].values()),
                        macro_recall=mean(v['recall'] for v in d['classMetrics'].values()),
                        ordinal_mae=mean(distances), ordinal_rmse=math.sqrt(mean(v*v for v in distances)),
                        mean_ms=d['latency']['meanMs'], p50_ms=d['latency']['medianMs'], p95_ms=d['latency']['p95Ms'])
        assert all(math.isclose(float(r[k]), v, abs_tol=1e-10) for k, v in expected.items())
        for c in [x for x in classes if x['source_json'] == r['source_json']]:
            assert all(math.isclose(float(c[k]), d['classMetrics'][c['label']][k], abs_tol=1e-10) for k in ['precision', 'recall', 'f1'])
            assert int(c['support']) == sum(x['truth'] == c['label'] for x in p)

    ordered = sorted(summary, key=lambda r: (int(r['seed']), r['variant'] != 'baseline', list(DEVICE).index(r['device']), r['runtime'] != 'onnx'))
    for a in [r for r in ordered if r['runtime'] == 'onnx']:
        b = next(r for r in ordered if (r['seed'], r['variant'], r['device'], r['runtime']) == (a['seed'], a['variant'], a['device'], 'pte'))
        pa, pb = [{x['id']: x['prediction'] for x in predictions if x['source_json'] == r['source_json']} for r in [a, b]]
        assert pa == pb and all(float(b[k]) < float(a[k]) for k in ['mean_ms', 'p50_ms', 'p95_ms'])
    quality, tradeoff = [], []
    for seed in ['159', '1024']:
        for variant in ['baseline', 'pruning']:
            group = [r for r in ordered if r['seed'] == seed and r['variant'] == variant]
            assert len(group) == 8
            quality.append([seed + (' B' if variant == 'baseline' else ' P')] +
                           [fmt(100 * mean(float(r[k]) for r in group)) for k in ['accuracy', 'macro_precision', 'macro_recall', 'macro_f1']])
            tradeoff.append([seed + (' B' if variant == 'baseline' else ' P')] +
                            [fmt(100 * mean(float(r[k]) for r in group)) for k in ['precision_high', 'recall_high']] +
                            [fmt(mean(float(r[k]) for r in group), 4) for k in ['ordinal_mae', 'ordinal_rmse']] +
                            [fmt(mean(severe[r['source_json']] for r in group))])
    table('phone-model-quality', 'Chất lượng phân loại trung bình của bốn phương án trên điện thoại (\%)',
          'tab:phone-model-quality', ['Phương án', 'Acc.', 'P macro', 'R macro', 'F1 macro'], quality)
    table('phone-model-tradeoffs', 'Đánh đổi phát hiện ngập cao và sai lệch mức ngập', 'tab:phone-model-tradeoffs',
          ['Phương án', r'P high (\%)', r'R high (\%)', 'MAE', 'RMSE', 'Lỗi nặng TB'], tradeoff)
    runtimes = []
    for device in DEVICE:
        a, b = [next(r for r in ordered if (r['seed'], r['variant'], r['device'], r['runtime']) == ('1024', 'pruning', device, t)) for t in ['onnx', 'pte']]
        pa, pb = [{x['id']: x['prediction'] for x in predictions if x['source_json'] == r['source_json']} for r in [a, b]]
        assert pa == pb
        for runtime, record in [('ONNX', a), ('PTE', b)]:
            runtimes.append([NAMES[device], runtime, fmt(float(record['p50_ms'])), fmt(float(record['p95_ms']))])
    table('phone-selected-runtimes', 'So sánh ONNX Runtime và ExecuTorch/PTE trên cùng điện thoại, model seed 1024 cắt tỉa', 'tab:phone-selected-runtimes',
          ['Điện thoại', 'Runtime', 'P50 (ms)', 'P95 (ms)'], runtimes)

    table('phone-full-quality', 'Chất lượng phân loại của đủ 32 cấu hình điện thoại (\%)', 'tab:phone-full-quality',
          ['Cấu hình', 'Acc.', 'P macro', 'R macro', 'F1 macro'],
          [[code(r)] + [fmt(100*float(r[k])) for k in ['accuracy', 'macro_precision', 'macro_recall', 'macro_f1']] for r in ordered], True)
    table('phone-full-ordinal', 'Sai lệch thứ bậc của đủ 32 cấu hình điện thoại', 'tab:phone-full-ordinal',
          ['Cấu hình', 'MAE (mức)', 'RMSE (mức)', 'Lỗi nặng/256'],
          [[code(r), fmt(r['ordinal_mae'], 4), fmt(r['ordinal_rmse'], 4), severe[r['source_json']]] for r in ordered], True)
    table('phone-full-latency', 'Thời gian xử lý ảnh của đủ 32 cấu hình điện thoại (ms)', 'tab:phone-full-latency',
          ['Cấu hình', 'Mean', 'P50', 'P95'],
          [[code(r)] + [fmt(r[k], 3) for k in ['mean_ms', 'p50_ms', 'p95_ms']] for r in ordered], True)
    perclass = []
    for r in ordered:
        for label in RANK:
            c = next(x for x in classes if x['source_json'] == r['source_json'] and x['label'] == label)
            perclass.append([code(r), label.replace('_', r'\_'), c['support']] + [fmt(100*float(c[k])) for k in ['precision', 'recall', 'f1']])
    table('phone-full-classes', 'Chỉ số từng lớp của đủ 32 cấu hình điện thoại (\%)', 'tab:phone-full-classes',
          ['Cấu hình', 'Lớp', 'Số ảnh', 'Precision', 'Recall', 'F1'], perclass, True)
    print('Validated 32 JSON sources; generated 3 main tables and 4 appendix tables (32/32/32/128 rows).')


if __name__ == '__main__':
    main()
