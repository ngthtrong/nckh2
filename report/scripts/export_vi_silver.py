#!/usr/bin/env python3
"""Export checked AI-silver pilot artifacts; this never trains or infers."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/revision-plan/outputs/vi-nlp-fusion-silver-20261108'
OUT = ROOT / 'report/generated'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(name):
    return json.loads((SOURCE / name).read_text())


def csv_rows(name):
    with (SOURCE / name).open(newline='') as f:
        return list(csv.DictReader(f))


def fmt(value):
    return f'{float(value):.2f}'.replace('.', ',')


def main():
    verification = read('verification.json')
    if verification['status'] != 'VERIFIED_WITHIN_AI_SILVER_PILOT':
        raise ValueError('Silver pilot has no technical verification receipt')
    if sha(SOURCE / 'evaluation.json') != verification['evaluation_sha256']:
        raise ValueError('Evaluation receipt changed')
    info = read('evaluation.json')
    for key, name in [('predictions_sha256', 'predictions.csv'), ('metrics_sha256', 'metrics.csv'),
                      ('paired_effects_sha256', 'paired-effects.csv')]:
        if sha(SOURCE / name) != info[key]:
            raise ValueError('Changed silver artifact: ' + name)
    data = read('dataset-lock.json')
    metrics = {r['model']: r for r in csv_rows('metrics.csv')}
    effects = csv_rows('paired-effects.csv')
    macros = ['% Generated from checked AI SILVER artifacts; not human/native Vietnamese gold.']
    values = {}
    for suffix, split in [('TrainN', 'train'), ('DevN', 'dev'), ('TestN', 'test')]:
        values[suffix] = sum(data['counts'][split].values())
    values['PositiveN'] = data['counts']['test']['request']
    values['NegativeN'] = data['counts']['test']['no_request']
    values['ExcludedN'] = data['excluded_uncertain']
    for prefix, model in [('Tfidf', 'T0'), ('Text', 'T1'), ('Image', 'I0'), ('Fusion', 'F1')]:
        values[prefix + 'FOne'] = fmt(100 * float(metrics[model]['macro_f1']))
    values['FusionRecall'] = fmt(100 * float(metrics['F1']['recall_request']))
    for prefix, model in [('Text', 'T1'), ('Image', 'I0'), ('Mean', 'P0')]:
        row = next(r for r in effects if r['comparator'] == model)
        for suffix, key in [('Delta', 'delta'), ('Low', 'ci_low'), ('High', 'ci_high')]:
            values['Fusion' + prefix + suffix] = fmt(100 * float(row[key]))
    fine = []
    if verification.get('T2', {}).get('status') == 'VERIFIED_T2_RECEIPTS_SELECTION_PREDICTIONS_AND_METRICS':
        if sha(SOURCE / 't2-evaluation.json') != verification['T2']['evaluation_receipt_sha256']:
            raise ValueError('Verified T2 evaluation receipt changed')
        t2 = read('t2-evaluation.json')
        if sha(SOURCE / 't2-metrics.csv') != t2['metrics_sha256']:
            raise ValueError('T2 metrics changed')
        update = read('encoder-update-check.json')
        if update['status'] != 'SELECTED_ENCODER_WEIGHTS_UPDATED' or len(update['checks']) != 3:
            raise ValueError('Missing actual encoder-update checks')
        checked = {(r['seed'], r['checkpoint_sha256']) for r in update['checks']}
        selected = {(r['seed'], r['checkpoint_sha256']) for r in read('t2-training.json')['selected_models']}
        if checked != selected or any(r['max_abs_change'] <= 0 for r in update['checks']):
            raise ValueError('Encoder-update checks differ from selected T2 checkpoints')
        fine = csv_rows('t2-metrics.csv')
        for suffix, key in [('FOne', 'macro_f1'), ('Accuracy', 'accuracy'), ('Recall', 'recall_request')]:
            vv = [100 * float(r[key]) for r in fine]
            values['Fine' + suffix] = fmt(mean(vv))
            values['Fine' + suffix + 'Low'] = fmt(min(vv))
            values['Fine' + suffix + 'High'] = fmt(max(vv))
    else:
        raise ValueError('T2 not verified; do not populate final fine-tuning table')
    for key, value in values.items():
        macros.append(r'\providecommand{\VISilver' + key + '}{' + str(value) + '}')
    (OUT / 'vi-silver-values.tex').write_text('\n'.join(macros) + '\n')
    names = [('B0', 'Lớp đa số'), ('T0', 'TF-IDF + LR'), ('T1', 'DistilBERT frozen + LR'),
             ('T2', 'DistilBERT fine-tuning (TB 3 seed)'), ('I0', 'Ảnh frozen + LR'),
             ('F0', 'TF-IDF + ảnh'), ('F1', 'DistilBERT frozen + ảnh'), ('P0', 'Trung bình xác suất'),
             ('F1_mask_image', 'Fusion che ảnh'), ('F1_mask_text', 'Fusion che văn bản')]
    table = [r'% Generated by export_vi_silver.py; do not edit.',
             r'\begin{table}[htbp]\centering',
             r'\caption{Pilot trên văn bản dịch tiếng Việt và nhãn AI: cùng 59 cặp test Sri Lanka, chỉ 6 nhãn request}\label{tab:vi-silver-pilot}',
             r'\begin{tabular}{P{.45\textwidth}rrr}\toprule',
             r'Cấu hình & Macro-F1 (\%) & Acc. (\%) & Recall (+) (\%) \\ \midrule']
    for model, name in names:
        if model == 'T2':
            numbers = [mean(float(r[k]) for r in fine) for k in ['macro_f1', 'accuracy', 'recall_request']]
        else:
            numbers = [float(metrics[model][k]) for k in ['macro_f1', 'accuracy', 'recall_request']]
        table.append(' & '.join([name] + [fmt(100 * value) for value in numbers]) + r' \\')
    table += [r'\bottomrule\end{tabular}', r'\end{table}']
    (OUT / 'tables/vi-silver-pilot.tex').write_text('\n'.join(table) + '\n')
    table = [r'% Generated by export_vi_silver.py; do not edit.', r'\begin{table}[htbp]\centering',
             r'\caption{Hiệu macro-F1 fusion frozen so với đối chứng trên nhãn AI; CI 95\% ghép cặp chưa hiệu chỉnh}\label{tab:vi-silver-effects}',
             r'\begin{tabular}{P{.42\textwidth}rrr}\toprule',
             r'Đối chứng & Hiệu (đpt) & Cận dưới & Cận trên \\ \midrule']
    labels = {'T1': 'DistilBERT frozen (chính)', 'I0': 'Ảnh frozen', 'P0': 'Trung bình xác suất'}
    for r in effects:
        table.append(' & '.join([labels[r['comparator']]] + [fmt(100 * float(r[k])) for k in ['delta', 'ci_low', 'ci_high']]) + r' \\')
    table += [r'\bottomrule\end{tabular}', r'\end{table}']
    (OUT / 'tables/vi-silver-effects.tex').write_text('\n'.join(table) + '\n')
    files = ['verification.json', 'evaluation.json', 'predictions.csv', 'metrics.csv', 'paired-effects.csv',
             'dataset-lock.json', 'features.json', 'training.json', 'protocol.json', 't2-protocol.json',
             't2-training.json', 't2-evaluation.json', 't2-predictions.csv', 't2-metrics.csv',
             'encoder-update-check.json']
    provenance = {str((SOURCE / name).relative_to(ROOT)): sha(SOURCE / name) for name in files}
    provenance[str(Path(__file__).relative_to(ROOT))] = sha(Path(__file__))
    (OUT / 'vi-silver-provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Exported translated AI-silver pilot: 2 tables and scoped values')


if __name__ == '__main__':
    main()
