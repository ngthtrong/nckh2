#!/usr/bin/env python3
"""Export report tables from saved artifacts; never train or modify experiment data."""
import csv
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'report/generated'
SOURCES = {}
PREDICTION_AUDITS = []


def read_bytes(relative):
    data = (ROOT / relative).read_bytes()
    SOURCES[relative] = hashlib.sha256(data).hexdigest()
    return data


def rows(relative):
    return list(csv.DictReader(read_bytes(relative).decode('utf-8-sig').splitlines()))


def obj(relative):
    return json.loads(read_bytes(relative))


def fmt(value, digits=4):
    return f'{float(value):.{digits}f}'


def verify_predictions(artifact, relative, split):
    predictions = rows(relative)
    test_paths = {r['relative_path'] for r in split if r['split'] == 'test'}
    paths = [r['image_path'].replace('\\', '/').split('/Dataset_Flood/', 1)[1]
             for r in predictions]
    if len(paths) != len(test_paths) or set(paths) != test_paths:
        raise ValueError(f'Prediction rows do not match held-out split: {relative}')
    classes = artifact['metadata']['class_order']
    for model, metrics in artifact['classification_metrics'].items():
        matrix = [[0] * len(classes) for _ in classes]
        for r in predictions:
            matrix[classes.index(r['ground_truth'])][classes.index(r['pred_' + model])] += 1
        accuracy = sum(matrix[i][i] for i in range(len(classes))) / len(predictions)
        f1 = sum(2 * matrix[i][i] / (sum(matrix[i]) + sum(row[i] for row in matrix))
                 for i in range(len(classes))) / len(classes)
        consistent = (matrix == metrics['confusion_matrix'] and abs(accuracy - metrics['accuracy']) <= 1e-10
                      and abs(f1 - metrics['macro_f1']) <= 1e-10)
        PREDICTION_AUDITS.append({'source': relative, 'model': model, 'consistent': consistent,
                                 'summary_accuracy': metrics['accuracy'], 'csv_accuracy': accuracy,
                                 'summary_macro_f1': metrics['macro_f1'], 'csv_macro_f1': f1})
        if not consistent:
            print(f'REVIEW REQUIRED: summary/prediction discrepancy: {relative}/{model}')


def table(name, caption, label, columns, headers, data, note):
    output = [r'% Generated by scripts/export_results.py; do not edit.',
              r'\begin{table}[htbp]\centering\small',
              r'\setlength{\tabcolsep}{3pt}' if name in ['rq2-robustness','image-metric-audit'] else '',
              r'\caption{' + caption + r'}\label{' + label + '}',
              r'\begin{tabular}{' + columns + '}', r'\toprule',
              ' & '.join(headers) + r' \\ \midrule']
    output.extend(' & '.join(map(str, row)) + r' \\' for row in data)
    output.extend([r'\bottomrule\end{tabular}', r'\SourceNote{' + note + '}', r'\end{table}', ''])
    (OUT / 'tables' / f'{name}.tex').write_text('\n'.join(output))


def main():
    (OUT / 'tables').mkdir(parents=True, exist_ok=True)
    split = rows('products/fe/model/Edge Ai/split_train_val_test_mobilenetv3_large.csv')
    counts = Counter((r['label'], r['split']) for r in split)
    classes = ['low', 'medium', 'high', 'non_flood']
    for row in split:
        file = ROOT / 'products/fe/model/Dataset_Flood' / row['relative_path']
        if not file.is_file() or hashlib.md5(file.read_bytes()).hexdigest() != row['md5']:
            raise ValueError(f"Missing or changed image: {row['relative_path']}")
    for field in ['md5', 'perceptual_group', 'split_group']:
        groups = defaultdict(set)
        for row in split:
            if row[field]:
                groups[row[field]].add(row['split'])
        if any(len(s) > 1 for s in groups.values()):
            raise ValueError(f'Cross-split overlap: {field}')
    table('image-split', 'Phân bố bộ ảnh hiện tại theo tệp chia tập đã lưu', 'tab:image-split',
          'lrrrr', ['Lớp', 'Train', 'Validation', 'Test', 'Tổng'],
          [[r'\texttt{' + c.replace('_', r'\_') + '}', *[counts[c, s] for s in ['train','val','test']],
            sum(counts[c,s] for s in ['train','val','test'])] for c in classes] +
          [['Tổng', *[sum(counts[c,s] for c in classes) for s in ['train','val','test']],len(split)]],
          r'\RepoPath{products/fe/model/Edge Ai/split_train_val_test_mobilenetv3_large.csv}; kiểm tra đường dẫn, MD5 và nhóm chia tập trên ảnh hiện tại.')
    base = obj('products/fe/reports/pth_onnx_pte/summary.json')
    quant = obj('products/fe/reports/fp32_ptq_qat/summary.json')
    pruning = obj('products/fe/reports/pruning_st/summary.json')
    for artifact in [base, quant, pruning]:
        metadata = artifact['metadata']
        expected_test_count = sum(r['split'] == 'test' for r in split)
        if metadata['evaluation_scope'] != 'full_test' or metadata['n_images'] != expected_test_count:
            raise ValueError('Image evaluation scope/count does not match split')
        if metadata['split_csv_sha256'] != SOURCES['products/fe/model/Edge Ai/split_train_val_test_mobilenetv3_large.csv']:
            raise ValueError('Image artifact split hash mismatch')
        if metadata['config_sha256'] != hashlib.sha256(read_bytes('products/fe/model/Edge Ai/config_mobilenetv3_large.json')).hexdigest():
            raise ValueError('Image artifact config hash mismatch')
    for name, artifact in [('pth_onnx_pte', base), ('fp32_ptq_qat', quant), ('pruning_st', pruning)]:
        verify_predictions(artifact, f'products/fe/reports/{name}/all_predictions.csv', split)
    def image_table(name, caption, artifact, models):
        data=[]
        for key,display in models:
            m=artifact['classification_metrics'][key]
            data.append([display,fmt(100*m['accuracy'],2),fmt(100*m['macro_f1'],2),
                         m['critical_error_count'],fmt(m['bytes']/1024**2,2),fmt(m['latency_ms_median'],2)])
        table(name,caption,'tab:'+name,'lrrrrr',
              ['Mô hình',r'Acc. (\%)',r'F1 (\%)','Lỗi nặng','MiB','Trung vị ms'],data,
              r'\RepoPath{products/fe/reports/'+name+r'/summary.json}; 256 ảnh test, CPU máy tính; thời gian chỉ tính lời gọi suy luận.')
    image_table('pth_onnx_pte','So sánh ba định dạng mô hình trên cùng tập test',base,
                [('pth','PyTorch FP32'),('onnx','ONNX FP32'),('pte','ExecuTorch FP32')])
    image_table('fp32_ptq_qat','PTQ/QAT theo summary đã lưu; số liệu nén cần rà soát',quant,
                [('onnx_fp32','ONNX FP32'),('ptq_int8','PTQ INT8'),('qat_int8','QAT INT8')])
    table('image-metric-audit', 'Đối chiếu các số liệu summary chưa khớp CSV dự đoán',
          'tab:image-metric-audit', 'lrrrr',
          ['Mô hình', r'\shortstack{Acc. summary\\(\%)}', r'\shortstack{Acc. CSV\\(\%)}', r'\shortstack{F1 summary\\(\%)}', r'\shortstack{F1 CSV\\(\%)}'],
          [[r['model'].replace('_', r'\_'), *[fmt(100*r[key], 2) for key in
            ['summary_accuracy','csv_accuracy','summary_macro_f1','csv_macro_f1']]]
          for r in PREDICTION_AUDITS if not r['consistent']],
          r'\RepoPath{products/fe/reports/fp32_ptq_qat/summary.json} và all\_predictions.csv cùng thư mục; giữ nguyên hai nguồn, chưa chốt metric nén.')
    image_table('pruning_st','Đối chiếu trước và sau cắt tỉa có cấu trúc',pruning,
                [('baseline_pth','PTH gốc'),('structured_pth','PTH cắt tỉa'),('baseline_onnx','ONNX gốc'),
                 ('structured_onnx','ONNX cắt tỉa'),('baseline_pte','PTE gốc'),('structured_pte','PTE cắt tỉa')])
    matrix=base['classification_metrics']['pth']['confusion_matrix']
    table('confusion','Ma trận nhầm lẫn FP32: hàng là nhãn thật, cột là dự đoán','tab:confusion',
          'lrrrr',['Nhãn','low','medium','high',r'non\_flood'],
          [[c.replace('_',r'\_'),*r] for c,r in zip(classes,matrix)],
          r'\RepoPath{products/fe/reports/pth_onnx_pte/summary.json}; tổng 256 ảnh.')
    metrics=base['classification_metrics']['pth']['per_class']
    table('image-classes','Chất lượng FP32 theo từng lớp','tab:image-classes','lrrrr',
          ['Lớp',r'Precision (\%)',r'Recall (\%)',r'F1 (\%)','Số ảnh'],
          [[c.replace('_',r'\_'),*[fmt(100*metrics[c][s],2) for s in ['precision','recall','f1']],metrics[c]['support']] for c in classes],
          r'\RepoPath{products/fe/reports/pth_onnx_pte/summary.json}.')
    benchmark=rows('thucnghiem/results/cij_baseline_benchmark_results/benchmark_summary.csv')
    names={'product_cij_louvain':'Product Louvain','additive_cij_louvain':'Additive Louvain',
           'convex_cij_louvain':'Convex Louvain','product_cij_leiden':'Product Leiden',
           'additive_cij_louvain_matched_density':'Additive mật độ khớp',
           'geo_time_dbscan':'Geo-time DBSCAN','kmeans':'K-means tọa độ',
           'spatial_agglomerative':'Gom cụm phân cấp','hdbscan':'HDBSCAN','dbscan':'DBSCAN mọi đặc trưng'}
    def method_name(key):
        if key in names:return names[key]
        if 'kmeans' in key:return 'K-means tọa độ'
        if 'agglomerative' in key:return 'Gom cụm phân cấp'
        if 'leiden' in key:return 'Product Leiden'
        if 'hdbscan' in key:return 'HDBSCAN'
        if 'dbscan' in key:return 'DBSCAN mọi đặc trưng'
        raise ValueError(key)
    table('rq1-benchmark','Kết quả RQ1 trên 40 run test của Generator 3.0','tab:rq1-benchmark','lrrr',
          ['Phương pháp',r'ARI [CI 95\%]','Pair F1','ĐK cụm (km)'],
          [[method_name(r['method']),fmt(r['ari_mean'])+' ['+fmt(r['ari_ci95_low'])+'; '+fmt(r['ari_ci95_high'])+']',
            fmt(r['pair_f1_mean']),fmt(r['mean_diameter_km'])] for r in sorted(benchmark,key=lambda x:-float(x['ari_mean']))],
          r'\RepoPath{thucnghiem/results/cij_baseline_benchmark_results/benchmark_summary.csv}; đường kính trung bình chỉ là thống kê mô tả.')
    stress=rows('thucnghiem/results/rq1_results/aggregate/rq1_stress_summary.csv')
    conditions=[('baseline','Đối chứng'),('gps_noise_100m','GPS 100 m'),('gps_noise_300m','GPS 300 m'),
                ('time_noise_15min','Thời gian 15 phút'),('time_noise_60min','Thời gian 60 phút'),
                ('exact_transport_copy_2x',r'Bản sao $2\times$'),('exact_transport_copy_5x',r'Bản sao $5\times$')]
    data=[]
    for key,display in conditions:
        group={r['method']:r for r in stress if r['scenario']==key}
        data.append([display,*[fmt(group[m]['ari_original_mean']) for m in
                              ['product_cij_louvain','additive_cij_louvain','product_cij_leiden','geo_time_dbscan']]])
    table('rq1-stress','ARI dưới nhiễu cố định; đánh giá trên báo cáo gốc có liên kết sự kiện','tab:rq1-stress',
          'lrrrr',['Điều kiện','Product','Additive','Leiden','DBSCAN'],data,
          r'\RepoPath{thucnghiem/results/rq1_results/aggregate/rq1_stress_summary.csv}; không gộp lần chạy lại trong rq1\_results\_v2.')
    align=rows('thucnghiem/results/rq2_results/rq2_summary.csv')
    display={'duplicate_aware_robust':'Điểm có chặn','legacy_raw':'Legacy','legacy':'Legacy','legacy_priority':'Legacy',
             'urgency_only':'Chỉ khẩn cấp','population_only':'Chỉ số người','simple_linear':'Tuyến tính','random':'Ngẫu nhiên'}
    data=[]
    for r in align:
        if r['section']=='alignment' and r['metric']=='ndcg_at_5':
            ci=json.loads(r['paired_confidence_interval'])
            data.append([display.get(r['method'],r['method'].replace('_',r'\_')),fmt(r['mean']),
                         '['+fmt(ci[0])+'; '+fmt(ci[1])+']'])
    table('rq2-alignment','NDCG@5 với nhóm sự kiện oracle trên 40 seed Candidate 4.1','tab:rq2-alignment',
          'lrr',['Điểm xếp hạng','NDCG@5',r'CI 95\%'],data,
          r'\RepoPath{thucnghiem/results/rq2_results/rq2_summary.csv}; nhóm oracle chỉ dùng cho chẩn đoán riêng tầng xếp hạng.')
    robustness_names = {
        'exact_duplicate_2x': r'Exact $2\times$', 'exact_duplicate_5x': r'Exact $5\times$',
        'exact_duplicate_10x': r'Exact $10\times$', 'near_duplicate': 'Gần trùng',
        'contradictory_F_E': r'Mâu thuẫn $F/E$', 'source_missingness_zero_imputation': 'Thiếu/điền 0',
        'low_confidence_inflate_E': r'Tăng $E$, confidence thấp',
        'low_confidence_inflate_F': r'Tăng $F$, confidence thấp',
        'low_confidence_inflate_N': r'Tăng $N$, confidence thấp',
        'low_confidence_inflate_V': r'Tăng $V$, confidence thấp',
        'coordinated_high_confidence_campaign': 'Phối hợp confidence cao'}
    robustness = [r for r in align if r['section'] == 'robustness']
    data = []
    for scenario in dict.fromkeys(r['scenario'] for r in robustness):
        row = [robustness_names.get(scenario, scenario.replace('_', r'\_'))]
        for metric in ['priority_drift_abs_normalized', 'mean_rank_drift_normalized', 'top_k_churn']:
            for method in ['duplicate_aware_robust', 'legacy_raw']:
                row.append(fmt(next(r['mean'] for r in robustness if r['scenario'] == scenario
                                    and r['metric'] == metric and r['method'] == method)))
        data.append(row)
    table('rq2-robustness', 'Độ nhạy RQ2: R là score có chặn, L là legacy; thấp hơn là tốt hơn',
          'tab:rq2-robustness', 'lrrrrrr',
          ['Điều kiện', r'$\Delta P_R$', r'$\Delta P_L$', r'$\Delta r_R$', r'$\Delta r_L$', 'Churn R', 'Churn L'], data,
          r'\RepoPath{thucnghiem/results/rq2_results/rq2_summary.csv}; thống kê mô tả perturbation trên split test.')
    sensitivity = rows('thucnghiem/results/rq2_results/rq2_parameter_sensitivity_summary.csv')
    data = []
    symbols = {'b0': r'$b_0$', 'b1': r'$b_1$', 'b2': r'$b_2$', 'omega_e': r'$\omega_E$',
               'omega_f': r'$\omega_F$', 'omega_n': r'$\omega_N$', 'mu': r'$\mu$', 's': '$s$',
               'n_ref': r'$N_{\mathrm{ref}}$', 'v_cap': r'$V_{\mathrm{cap}}$'}
    for parameter in dict.fromkeys(r['parameter'] for r in sensitivity):
        r = next(r for r in sensitivity if r['parameter'] == parameter)
        data.append([symbols[parameter], '[' + fmt(r['metric_range_min']) + '; ' + fmt(r['metric_range_max']) + ']',
                     fmt(r['metric_range_span'], 5), r['n_test_seeds']])
    table('rq2-sensitivity', 'Khoảng NDCG@5 trung bình trong phân tích hằng số cục bộ RQ2',
          'tab:rq2-sensitivity', 'lrrr', ['Hằng số', 'Min--max NDCG@5', 'Span', 'Seed'], data,
          r'\RepoPath{thucnghiem/results/rq2_results/rq2_parameter_sensitivity_summary.csv}; mỗi lần chỉ thay một hằng số, trọng số được chuẩn hóa lại.')
    comparisons=rows('thucnghiem/results/rq3_results/rq3_paired_comparisons_seed.csv')
    data=[]
    for comp,display_name in [('legacy_priority','Legacy'),('nearest_first','Gần nhất trước')]:
        for metric,metric_name in [('latent_harm','Harm'),('deadline_miss_rate','Trễ hạn (đpt)')]:
            r=next(r for r in comparisons if r['dimension']=='policy' and r['candidate']=='revised_priority'
                   and r['comparator']==comp and json.loads(r['fixed'])['partition']=='product_cij' and r['metric']==metric)
            scale=100 if metric=='deadline_miss_rate' else 1
            ci=json.loads(r['paired_confidence_interval'])
            data.append([display_name,metric_name,fmt(scale*float(r['mean']),2),
                         '['+fmt(scale*ci[0],2)+'; '+fmt(scale*ci[1],2)+']',fmt(r['holm_adjusted_p_value'],6)])
    table('rq3-effects','So sánh điểm có chặn trên phân hoạch Product: 40 cặp seed','tab:rq3-effects',
          'llrrr',['Đối chứng','Chỉ số',r'$\Delta$ cải thiện',r'CI 95\%',r'$p_{\mathrm{Holm}}$'],data,
          r'\RepoPath{thucnghiem/results/rq3_results/rq3_paired_comparisons_seed.csv}; giá trị dương có lợi cho điểm có chặn; đpt = điểm phần trăm.')
    read_bytes('paper/main.tex')
    for relative in ['thucnghiem/results/rq1_results/manifest.json',
                     'thucnghiem/results/rq2_results/rq2_artifact_sha256.json',
                     'thucnghiem/results/rq3_results/rq3_seed_level_reanalysis_provenance.json',
                     'products/fe/model/urgency_ei/model/urgency_logistic_SOURCE_FINAL.json']:
        read_bytes(relative)
    m=base['classification_metrics']['pth']
    values={'ImageTotal':len(split),
            'ImageTrain':sum(r['split'] == 'train' for r in split),
            'ImageVal':sum(r['split'] == 'val' for r in split),
            'ImageTest':sum(r['split'] == 'test' for r in split),
            'ImageAccuracy':fmt(100*m['accuracy'],2),'ImageMacroFOne':fmt(100*m['macro_f1'],2),
            'PTQAccuracy':fmt(100*quant['classification_metrics']['ptq_int8']['accuracy'],2),
            'QATAccuracy':fmt(100*quant['classification_metrics']['qat_int8']['accuracy'],2)}
    (OUT/'values.tex').write_text('% Generated from saved artifacts by scripts/export_results.py.\n'+
                                ''.join('\\newcommand{\\'+k+'}{'+str(v)+'}\n' for k,v in values.items()))
    snapshot={'source_commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),
              'sources_sha256':SOURCES,'image_audit':{'rows':len(split),'missing':0,'md5_mismatch':0,'cross_split_groups':0},
              'prediction_audits': PREDICTION_AUDITS,
              'note':'Saved artifacts only; no training or mobile benchmark rerun. Source commit does not include report edits. PTQ/QAT summary discrepancies are disclosed in the report, not repaired.'}
    (OUT/'provenance.json').write_text(json.dumps(snapshot,ensure_ascii=False,indent=2)+'\n')
    print(f'Exported 13 tables from {len(SOURCES)} source files; verified {len(split)} images; audited saved predictions with disclosed PTQ/QAT discrepancies.')


if __name__=='__main__':
    main()
